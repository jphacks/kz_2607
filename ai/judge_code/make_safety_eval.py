PET_LINES = [None, "きみ、どうしたの？", "ぼく、きみとお話ししたいな", "今日はなにしてたの？", "ねえねえ、きいて！"]


def build(seed=1):
    rng = random.Random(seed)
    items = ([(t, ["暴言"]) for t in ABUSE] + [(t, ["差別"]) for t in DISCRIMINATION]
             + [(t, ["性的"]) for t in SEXUAL] + [(t, []) for t in ROUGH_BUT_SAFE])
    rows = []
    for i, (text, safety) in enumerate(items):
        pet = rng.choice(PET_LINES)
        turns = ([{"speaker": "pet", "text": pet}] if pet else []) + [{"speaker": "owner", "text": text}]
        rows.append({"id": f"seval{i:03d}", "turns": turns, "labels": {"safety": safety},
                     "split": "dev" if i % 2 == 0 else "test"})
    return rows


