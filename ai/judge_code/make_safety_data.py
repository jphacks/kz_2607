PET_LINES = [
    None, "きみ、なにしてるの？", "ぼく、おなかすいたなあ", "今日はどんな日だった？",
    "いっしょにお話ししよ！", "ぼく、ちょっとねむいや", "きみ、元気ないね？",
]
PREFIXES = ["", "なあ、", "ねえ、"]


def variants(text, rng):
    """言い方のゆれ（文字起こし風に句読点を消す・前後に口ぐせを付ける）を作る"""
    out = {text, re.sub(r"[、。！？!?]", "", text)}           # 句読点なし（文字起こし風）
    out.add(rng.choice(["マジで", "ほんまに", "おい、", "ってか"]) + text)
    out.add(text + rng.choice(["笑", "わ", "って", "まじで"]))
    return sorted(out)


def build(seed=0):
    rng = random.Random(seed)
    rows = []

    def add(text, safety, kind):
        for prefix in rng.sample(PREFIXES, 1):
            pet = rng.choice(PET_LINES)
            turns = ([{"speaker": "pet", "text": pet}] if pet else []) + \
                    [{"speaker": "owner", "text": prefix + text}]
            rows.append({"id": f"safe{len(rows):04d}", "turns": turns,
                         "labels": {"safety": safety}, "meta": {"source": "make_safety_data", "kind": kind}})

    for t in ABUSE:
        for v in variants(t, rng):
            add(v, ["暴言"], "暴言")
    for t in DISCRIMINATION:
        for v in variants(t, rng):
            add(v, ["差別"], "差別")
    for t in SEXUAL:
        for v in variants(t, rng):
            add(v, ["性的"], "性的")
    for t in ROUGH_BUT_SAFE:
        for v in variants(t, rng):               # まぎらわしい安全な例も同じだけゆらす
            add(v, [], "くだけた安全")
    rng.shuffle(rows)
    return rows


